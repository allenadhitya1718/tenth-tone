// A post's place (0101). Absent on a database without 0101 and null on a
// post with no place; lat and lng are always both set or both null.
export type VideoPlace = { name: string; lat: number; lng: number };
export type PlacedVideo = Video & { place_name?: string | null; lat?: number | null; lng?: number | null };
export type PlacedVideoRow = VideoRow & { place_name?: string | null; lat?: number | null; lng?: number | null };

export type PublishResult = {
  video: PlacedVideoRow;
  // Tags the database refused. The post itself succeeded; show these.
  tagRefusals: TagRefusal[];
};

