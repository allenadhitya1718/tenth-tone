// ---------- Deleting ----------

// Deleting your own post, and its media. 0068 left the bytes in R2 because a
// delete path that could remove the wrong file is worse than paying for
// orphans; that check now lives in the Edge Function, which refuses unless
// the object is yours and nothing references it. The orphans were also
// world-readable copies of something a person asked to delete.
// Invalidate videoKeys.feed and videoKeys.userVideos afterwards.
export async function deleteVideo(videoId: Uuid): Promise<true> {
  // Read the URLs while the row still exists; nothing else records which
  // objects belonged to which post. A failure here costs only the cleanup.
  let media: (string | null)[] = [];
  try {
    const { data: v } = await supabase.from('videos').select('video_url, thumbnail').eq('id', videoId).maybeSingle();
    const row = v as { video_url: string | null; thumbnail: string | null } | null;
    if (row) media = [row.video_url, row.thumbnail];
  } catch {}

  // .select() so a policy-blocked delete (removes nothing, raises nothing)
  // is distinguishable from a real one.
  const { data, error } = await supabase.from('videos').delete().eq('id', videoId).select('id');
  if (error) throw error;
  if (!data || !data.length) throw new ApiError('video_delete_forbidden');

  // Only on a delete that really happened.
  releaseMedia(media);
  return true;
}

