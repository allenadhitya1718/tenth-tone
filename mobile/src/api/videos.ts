type FypRow = {
  id: Uuid;
  description: string | null;
  music: string | null;
  sound_id: Uuid | null;
  video_url: string | null;
  thumbnail: string | null;
  privacy: Privacy;
  likes_count: number;
  comments_count: number;
  shares_count: number;
  views_count: number;
  created_at: Iso;
  user_id: Uuid;
  user_name: string | null;
  user_handle: string | null;
  user_avatar_url: string | null;
  user_verified: boolean | null;
  // Since 0084. Absent on an older installed function.
  saves_count?: number;
  liked?: boolean;
  saved?: boolean;
  following?: boolean;
};

// While being assembled, saves_count may still be unknown.
type FeedVideo = Omit<Video, 'saves_count'> & { saves_count?: number };

export async function fetchFeed({
  tab = 'foryou',
  limit = 20,
  offset = 0,
}: { tab?: FeedTab | string; limit?: number; offset?: number } = {}): Promise<Video[]> {
  let data: FeedVideo[] = [];

  if (tab === 'foryou') {
    try {
      const p_user_id = await uid();
      const { data: rpcData, error: rpcErr } = await supabase.rpc('fetch_fyp_feed', { p_limit: limit, p_offset: offset, p_user_id });
      const rows = rpcData as FypRow[] | null;
      if (!rpcErr && rows && rows.length) {
        data = rows.map((r) => ({
          id: r.id,
          description: r.description,
          music: r.music,
          sound_id: r.sound_id,
          video_url: r.video_url,
          thumbnail: r.thumbnail,
          privacy: r.privacy,
          likes_count: r.likes_count,
          comments_count: r.comments_count,
          shares_count: r.shares_count,
          views_count: r.views_count,
          created_at: r.created_at,
          user: {
            id: r.user_id,
            name: r.user_name,
            handle: r.user_handle,
            avatar_url: r.user_avatar_url,
            verified: r.user_verified,
          },
          // Since 0084 the function answers these itself, so the feed is ONE
          // round trip. Left undefined for an older function; the lookups
          // below fill them in.
          saves_count: typeof r.saves_count === 'number' ? r.saves_count : undefined,
          liked: typeof r.liked === 'boolean' ? r.liked : undefined,
          saved: typeof r.saved === 'boolean' ? r.saved : undefined,
          following: typeof r.following === 'boolean' ? r.following : undefined,
        }));
      }
    } catch (err) {
      console.warn('FYP RPC fallback to standard query:', err);
    }
  }

  if (!data.length) {
    let q = supabase
      .from('videos')
      .select(FEED_COLUMNS)
      .eq('is_draft', false)
      .eq('privacy', 'public')
      .order('created_at', { ascending: false });

    if (tab === 'following') {
      const me = await uid();
      if (!me) return [];
      const { data: f } = await supabase.from('follows').select('followed_id').eq('follower_id', me);
      const ids = ((f ?? []) as { followed_id: Uuid }[]).map((r) => r.followed_id);
      if (!ids.length) return [];
      q = q.in('user_id', ids);
    }

    const { data: fetched, error } = await q.range(offset, offset + limit - 1);
    if (error) throw error;
    data = (fetched ?? []) as unknown as FeedVideo[];
  }

  // Everything below only runs for rows the function did not answer (the
  // plain-query fallback, or a pre-0084 function), and all of it runs AT
  // ONCE: each lookup is 0.2-1.0 s from a phone and nothing can be drawn
  // until they are all back.
  //
  // saves_count: the old fetch_fyp_feed did not return it, the feed showed 0
  // and the optimistic +1 from saving was wiped by the next repaint. The
  // column is kept correct by the tr_saves_count trigger, so read it directly.
  const me = await uid();
  const lookups: Promise<void>[] = [];
  if (data.length && data.some((v) => v.saves_count == null)) {
    lookups.push(
      (async () => {
        try {
          const missing = data.filter((v) => v.saves_count == null).map((v) => v.id);
          const { data: counts } = await supabase.from('videos').select('id, saves_count').in('id', missing);
          const bySaves = new Map(((counts ?? []) as { id: Uuid; saves_count: number }[]).map((r) => [r.id, r.saves_count]));
          data.forEach((v) => {
            if (v.saves_count == null) v.saves_count = bySaves.get(v.id) || 0;
          });
        } catch {
          data.forEach((v) => {
            if (v.saves_count == null) v.saves_count = 0;
          });
        }
      })(),
    );
  }

  // Which of these I already liked / saved.
  if (me && data.length && data.some((v) => v.liked == null || v.saved == null)) {
    lookups.push(
      (async () => {
        const ids = data.map((v) => v.id);
        const [{ data: likes }, { data: saves }] = await Promise.all([
          supabase.from('likes').select('video_id').eq('user_id', me).in('video_id', ids),
          supabase.from('saves').select('video_id').eq('user_id', me).in('video_id', ids),
        ]);
        const likeSet = new Set(((likes ?? []) as { video_id: Uuid }[]).map((r) => r.video_id));
        const saveSet = new Set(((saves ?? []) as { video_id: Uuid }[]).map((r) => r.video_id));
        data.forEach((v) => {
          if (v.liked == null) v.liked = likeSet.has(v.id);
          if (v.saved == null) v.saved = saveSet.has(v.id);
        });
      })(),
    );
  }

  // Which of these creators I follow: one query for the page, instead of
  // one per card after drawing.
  if (me && data.length && data.some((v) => v.following == null)) {
    lookups.push(
      (async () => {
        try {
          const creators = Array.from(
            new Set(data.filter((v) => v.following == null && v.user?.id).map((v) => v.user!.id)),
          );
          if (!creators.length) return;
          const { data: rows } = await supabase
            .from('follows')
            .select('followed_id')
            .eq('follower_id', me)
            .in('followed_id', creators);
          const followed = new Set(((rows ?? []) as { followed_id: Uuid }[]).map((r) => r.followed_id));
          data.forEach((v) => {
            if (v.following == null && v.user) v.following = followed.has(v.user.id);
          });
        } catch {
          /* the per-card follow lookup is the last resort */
        }
      })(),
    );
  }
  if (lookups.length) await Promise.all(lookups);
  if (!me) {
    data.forEach((v) => {
      if (v.liked == null) v.liked = false;
      if (v.saved == null) v.saved = false;
    });
  }
  return data as Video[];
}

// ---------- Single video, a user's grid ----------

// Used by deep links (/v/<id>) to pin a shared video to the top of the feed.
// A single video, e.g. from a deep link. Unlike db.js this also carries
// saves_count, the comment/saving switches and the viewer's liked / saved /
// following flags, so a deep-linked video renders exactly like a feed card.
export async function fetchVideo(videoId: Uuid): Promise<Video | null> {
  const { data, error } = await supabase
    .from('videos')
    .select(
      `
      id, description, music, sound_id, video_url, thumbnail, privacy,
      likes_count, comments_count, shares_count, saves_count, views_count, created_at,
      allow_comments, allow_saving,
      user:profiles!videos_user_id_fkey ( id, name, handle, avatar_url, verified )
    `,
    )
    .eq('id', videoId)
    .maybeSingle();
  if (error) throw error;
  const video = (data as unknown as Video | null) ?? null;
  if (!video) return null;

  const me = await uid();
  if (!me) return { ...video, liked: false, saved: false, following: false };
  const creator = video.user?.id;
  const [liked, saved, following] = await Promise.all([
    supabase.from('likes').select('video_id').eq('user_id', me).eq('video_id', videoId).maybeSingle(),
    supabase.from('saves').select('video_id').eq('user_id', me).eq('video_id', videoId).maybeSingle(),
    creator && creator !== me
      ? supabase.from('follows').select('followed_id').eq('follower_id', me).eq('followed_id', creator).maybeSingle()
      : Promise.resolve({ data: null }),
  ]);
  return { ...video, liked: !!liked.data, saved: !!saved.data, following: !!following.data };
}

// Pinned videos first, newest first within each group.
export async function fetchUserVideos(userId: Uuid | null | undefined): Promise<VideoTile[]> {
  if (!userId) return [];
  const { data, error } = await supabase
    .from('videos')
    .select(`${TILE_COLUMNS}, is_pinned`)
    .eq('user_id', userId)
    .eq('is_draft', false)
    .eq('is_archived', false)
    .order('is_pinned', { ascending: false })
    .order('created_at', { ascending: false });
  if (error) throw error;
  return (data ?? []) as VideoTile[];
}

// Pin / unpin one of your own videos. The 3-per-user cap is a database
// trigger, so this surfaces its error rather than guessing.
export async function setVideoPinned(videoId: Uuid, pinned: boolean): Promise<void> {
  const me = await requireUid();
  const { error } = await supabase.from('videos').update({ is_pinned: !!pinned }).eq('id', videoId).eq('user_id', me);
  if (error) {
    if (/pin limit reached/i.test(error.message || '')) throw new ApiError('pin_limit_reached', error.message);
    throw error;
  }
}

