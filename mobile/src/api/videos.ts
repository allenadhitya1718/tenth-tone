// Videos: publishing, the feed, single videos, drafts, archive, pins,
// deletion, likes and saves, the "your activity" lists, feed feedback and
// engagement tracking, and the upload quota. Port of the matching parts of
// web/js/db.js. Caching is TanStack Query's job; see videoKeys.
//
// ApiError codes introduced here:
//   content_blocked        moderation refused the post (message carries the
//                          server's Arabic text)
//   draft_publish_failed   the draft could not be published (no row updated)
//   pin_limit_reached      already 3 pinned videos (database trigger)
//   video_delete_forbidden the delete removed nothing (not yours, or 0068
//                          not applied)
// Also thrown: 'not_signed_in' (client.ts) and the upload.ts codes. Tag
// refusals on publish are returned, not thrown (see tags.ts for the reasons).
