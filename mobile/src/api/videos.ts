// ---------- Publishing ----------

export type PublishInput = {
  video: LocalMedia;
  // Generated by the caller (a frame a little way into the clip). Optional:
  // without one the video URL doubles as the thumbnail.
  poster?: LocalMedia | null;
  // Small frames for screening. Defaults to the poster alone.
  frames?: ScreenImage[] | null;
  description?: string | null;
  music?: string | null;
  sound_id?: Uuid | null;
  privacy?: Privacy;
  is_draft?: boolean;
  allow_comments?: boolean;
  allow_saving?: boolean;
  // Client note 21. Both need 0101; leave them out on a database without it.
  place?: VideoPlace | null;
  tags?: Uuid[];
  onProgress?: Progress;
};

// The columns for a place, shaped to pass 0101's checks: a name of 1-120
// characters, and coordinates in range and in pairs. A bad coordinate is
// dropped rather than sent, because a check failure would fail the whole
// post after its upload.
function placeColumns(place: VideoPlace) {
  const place_name = (place.name ?? '').trim().slice(0, 120) || null;
  const ok =
    Number.isFinite(place.lat) && Number.isFinite(place.lng) && Math.abs(place.lat) <= 90 && Math.abs(place.lng) <= 180;
  // Privacy (PHASE4 notes): a post keeps the area of a place, not anyone's
  // exact position. Three decimals is about 100 m; the picker already rounds,
  // this holds for any other caller.
  const r3 = (n: number) => Math.round(n * 1000) / 1000;
  return { place_name, lat: ok ? r3(place.lat) : null, lng: ok ? r3(place.lng) : null };
}

export async function publishVideo({
  video,
  poster = null,
  frames,
  description,
  music,
  sound_id = null,
  privacy = 'public',
  is_draft = false,
  allow_comments = true,
  allow_saving = true,
  place = null,
  tags = [],
  onProgress,
}: PublishInput): Promise<PublishResult> {
  const userId = await requireUid();

  // Screening runs CONCURRENTLY with the upload and is awaited just above
  // the videos insert. That costs nothing in safety: the clip becomes visible
  // at the insert, not at the upload, and the insert is gated on the verdict.
  // What it buys is the wait (a scan is ~3-6 s, the upload ~5-6 s; in
  // sequence that was a ~10 s publish). A refused clip's bytes sit in R2
  // until released below.
  // Drafts are screened too: a draft becomes a post with one tap.
  // .catch here, not at the await: if the upload throws first nothing would
  // consume this promise and it would surface as an unhandled rejection.
  const screening = checkVideo(frames ?? (poster ? [poster] : []), description).catch(() => null);

  // No separate quota pre-flight: media-upload runs upload_quota_status()
  // itself before it signs anything and compares the declared size against
  // the ceiling, so asking here as well was a wasted round trip per upload.
  const video_url = await uploadToR2(video, onProgress);

  // A failed poster never fails the post; the video URL stands in for it.
  let poster_url: string | null = null;
  if (poster) {
    try {
      poster_url = await uploadToR2(poster);
    } catch (e) {
      console.warn('poster:', (e as Error)?.message);
    }
  }

  // The gate. Everything above is reversible (bytes with no row pointing at
  // them) and nothing above is visible to anyone.
  const verdict = await screening;
  if (verdict?.blocked) {
    // Nothing points at the uploaded bytes, so hand them back now rather
    // than leave them counting against the quota until the hourly sweep.
    releaseMedia([video_url, poster_url]);
    throw new ApiError('content_blocked', verdict.message ?? undefined);
  }

  const { data, error } = await supabase
    .from('videos')
    .insert({
      user_id: userId,
      description: description || '',
      music: music || null,
      sound_id,
      video_url,
      thumbnail: poster_url || video_url,
      privacy,
      is_draft,
      allow_comments,
      allow_saving,
      // Only with a place, so a post without one still works on a database
      // that has no place columns yet.
      ...(place ? placeColumns(place) : {}),
    })
    .select()
    .single();
  if (error) throw error;
  const row = data as PlacedVideoRow;

  // Tags need the row to exist. A refused tag never fails the post: the
  // refusals go back to the screen to show.
  let tagRefusals: TagRefusal[] = [];
  if (tags.length && row?.id) {
    try {
      tagRefusals = (await addVideoTags(row.id, tags)).refused;
    } catch (e) {
      tagRefusals = tags.map((userId) => ({ userId, reason: 'tag_failed', message: (e as Error)?.message }));
    }
  }

  // Not awaited and cannot throw: filing the queue entry is bookkeeping.
  if (verdict && row?.id) void attach(verdict, 'video', row.id);

  // Every PUBLIC post gets an original sound others can reuse. Skipped when
  // an existing sound was picked, for drafts, and for anything not public.
  // The last rule is a privacy fix: `sounds` is readable by anyone, signed in
  // or not, and the sound's audio_url IS the video's own URL (the mp4's audio
  // track is played directly). Writing one for a private clip published its
  // media URL to a world-readable table. 0079 enforces the same rule in RLS.
  if (!sound_id && !is_draft && privacy === 'public' && row?.id) {
    try {
      const snd = await createOriginalSound({ videoId: row.id, title: 'صوت أصلي', coverUrl: poster_url, audioUrl: video_url });
      if (snd?.id) {
        await supabase.from('videos').update({ sound_id: snd.id }).eq('id', row.id);
        row.sound_id = snd.id;
      }
    } catch (e) {
      console.warn('original sound:', e); // never block a post
    }
  }
  return { video: row, tagRefusals };
}

