const EMBEDDED_TILE = `
  id, description, thumbnail, video_url, likes_count, created_at,
  user:profiles!videos_user_id_fkey ( id, name, handle, avatar_url )
`;

// Videos the given user (default: me) liked. Backs the profile "Liked" tab.
export async function fetchLikedVideos(userId?: Uuid | null): Promise<VideoTile[]> {
  const target = userId || (await uid());
  if (!target) return [];
  const { data, error } = await supabase
    .from('likes')
    .select(`created_at, video:videos!likes_video_id_fkey ( ${EMBEDDED_TILE} )`)
    .eq('user_id', target)
    .order('created_at', { ascending: false })
    .limit(60);
  if (error) throw error;
  return ((data ?? []) as unknown as { video: VideoTile | null }[]).map((r) => r.video).filter((v): v is VideoTile => !!v);
}

// Saves are private, so this is always the signed-in user's own list.
export async function fetchSavedVideos(): Promise<VideoTile[]> {
  const me = await uid();
  if (!me) return [];
  const { data, error } = await supabase
    .from('saves')
    .select(`created_at, video:videos!saves_video_id_fkey ( ${EMBEDDED_TILE} )`)
    .eq('user_id', me)
    .order('created_at', { ascending: false })
    .limit(60);
  if (error) throw error;
  return ((data ?? []) as unknown as { video: VideoTile | null }[]).map((r) => r.video).filter((v): v is VideoTile => !!v);
}

// ---------- Your activity ----------
// What you did, not what was done to you (that is notifications).

export type MyLikedVideo = Pick<Video, 'id' | 'thumbnail' | 'description' | 'likes_count'> & { acted_at: Iso };

export async function fetchMyLikedVideos(limit = 60): Promise<MyLikedVideo[]> {
  const me = await uid();
  if (!me) return [];
  const { data, error } = await supabase
    .from('likes')
    .select('created_at, videos:videos!likes_video_id_fkey(id, thumbnail, description, likes_count)')
    .eq('user_id', me)
    .order('created_at', { ascending: false })
    .limit(limit);
  if (error) throw error;
  type Row = { created_at: Iso; videos: Omit<MyLikedVideo, 'acted_at'> | null };
  return ((data ?? []) as unknown as Row[])
    .map((r) => (r.videos ? { ...r.videos, acted_at: r.created_at } : null))
    .filter((v): v is MyLikedVideo => !!v);
}

export type ContentCounts = { posts: number; likes: number; comments: number; archived: number };

export async function countMyContent(): Promise<ContentCounts> {
  const me = await uid();
  if (!me) return { posts: 0, likes: 0, comments: 0, archived: 0 };
  const one = async (table: string, filters: Record<string, boolean> = {}) => {
    let q = supabase.from(table).select('*', { count: 'exact', head: true }).eq('user_id', me);
    for (const [col, val] of Object.entries(filters)) q = q.eq(col, val);
    const { count } = await q;
    return count || 0;
  };
  const [posts, likes, comments, archived] = await Promise.all([
    one('videos', { is_draft: false, is_archived: false }),
    one('likes'),
    one('comments'),
    one('videos', { is_archived: true }),
  ]);
  return { posts, likes, comments, archived };
}

// ---------- Feed signals ----------

// Interested / not interested: a negative signal for the feed algorithm.
export async function setVideoFeedback(videoId: Uuid, feedback: string): Promise<void> {
  if (!videoId || typeof videoId !== 'string' || videoId.length < 10) return;
  await requireUid();
  const { error } = await supabase.rpc('set_video_feedback', { p_video_id: videoId, p_feedback: feedback });
  if (error) throw error;
}

// Feeds the personalised For You algorithm. Never throws.
export async function trackEngagement({
  videoId,
  watchMs = 0,
  loopCount = 0,
  completionPct = 0,
}: {
  videoId: Uuid;
  watchMs?: number;
  loopCount?: number;
  completionPct?: number;
}): Promise<void> {
  if (!videoId || typeof videoId !== 'string' || videoId.length < 10) return; // placeholder ids
  const me = await uid();
  if (!me) return; // only signed-in users build a preference profile
  const { error } = await supabase.rpc('track_engagement', {
    p_video_id: videoId,
    p_watch_ms: Math.round(watchMs),
    p_loop_count: loopCount,
    p_completion_pct: Math.max(0, Math.min(1, completionPct)),
  });
  if (error) console.warn('trackEngagement failed:', error.message);
}

// ---------- Upload quota ----------
// Neither storage provider offers a hard spending cap, so the ceiling is
// enforced by the server (media-upload and a storage policy). This is only
// for SHOWING the reason; it never gates an upload itself.

export type UploadQuota = {
  allowed: boolean;
  reason?: 'daily_count' | 'daily_bytes' | 'global_full' | (string & {}) | null;
  uploads_limit?: number;
  max_video_bytes?: number;
  [field: string]: unknown;
};

export async function uploadQuota(): Promise<UploadQuota | null> {
  const me = await uid();
  if (!me) return null;
  const { data, error } = await supabase.rpc('upload_quota_status');
  if (error) return null; // migration not applied: do not block uploads
  return data as UploadQuota;
}

// The web version returned an Arabic sentence. This returns a message code
// for the screen to translate ('' when uploading is allowed); the
// daily_count message also needs q.uploads_limit.
export type QuotaMessageCode = '' | 'quota_daily_count' | 'quota_daily_bytes' | 'quota_global_full' | 'quota_unavailable';

export function quotaMessage(q: UploadQuota | null | undefined): QuotaMessageCode {
  if (!q || q.allowed) return '';
  if (q.reason === 'daily_count') return 'quota_daily_count';
  if (q.reason === 'daily_bytes') return 'quota_daily_bytes';
  if (q.reason === 'global_full') return 'quota_global_full';
  return 'quota_unavailable';
}

