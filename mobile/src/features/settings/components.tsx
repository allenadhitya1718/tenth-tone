export function ErrorView({ message, onRetry }: { message?: string; onRetry?: () => void }) {
  const { colors } = useTheme();
  const { t } = useTranslation();
  return (
    <View style={styles.center} accessibilityLiveRegion="polite">
      <Ionicons name="cloud-offline-outline" size={36} color={colors.muted} />
      <AppText center muted style={{ marginTop: 10 }} accessibilityRole="alert">
        {message ?? t('settings2.common.loadFailed')}
      </AppText>
      {onRetry ? (
        <Button title={t('settings2.common.retry')} variant="secondary" onPress={onRetry} style={styles.retry} />
      ) : null}
    </View>
  );
}

