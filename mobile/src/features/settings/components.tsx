// Building blocks shared by every settings screen: grouped cards, rows,
// switches, radio rows, people rows and the loading / error / empty states.
import { Ionicons } from '@expo/vector-icons';
import * as Haptics from 'expo-haptics';
import { Image } from 'expo-image';
import { router, type Href } from 'expo-router';
import type { TFunction } from 'i18next';
import { Children, Fragment, type ComponentProps, type ReactNode } from 'react';
import { useTranslation } from 'react-i18next';
import { ActivityIndicator, Alert, I18nManager, Pressable, StyleSheet, Switch, Text, View } from 'react-native';

import { ApiError } from '@/api/client';
import { AppText, Button } from '@/components/ui';
import { useTheme } from '@/providers/ThemeProvider';

export type IconName = ComponentProps<typeof Ionicons>['name'];

// Settings routes are pushed, never replaced, so the list underneath stays
// mounted and keeps its scroll position (client note 15). Typed routes are
// generated by Metro, so new paths go through a plain string here.
export function go(path: string) {
  router.push(path as Href);
}

// "Forward" points left in a right-to-left layout.
export const forwardChevron = (): IconName => (I18nManager.isRTL ? 'chevron-back' : 'chevron-forward');

export function tick() {
  Haptics.selectionAsync().catch(() => {});
}

// ---------- Groups ----------

export function Group({ title, footer, children }: { title?: string; footer?: string; children: ReactNode }) {
  const { colors } = useTheme();
  const items = Children.toArray(children).filter(Boolean);
  return (
    <View style={styles.group}>
      {title ? (
        <AppText variant="small" muted style={styles.groupTitle} accessibilityRole="header">
          {title}
        </AppText>
      ) : null}
      <View style={[styles.card, { backgroundColor: colors.bg2 }]}>
        {items.map((child, i) => (
          <Fragment key={i}>
            {i > 0 ? <View style={[styles.sep, { backgroundColor: colors.border }]} /> : null}
            {child}
          </Fragment>
        ))}
      </View>
      {footer ? (
        <AppText variant="small" muted style={styles.footer}>
          {footer}
        </AppText>
      ) : null}
    </View>
  );
}

export function Note({ children }: { children: ReactNode }) {
  return (
    <AppText variant="small" muted style={styles.note}>
      {children}
    </AppText>
  );
}

function RowIcon({ name, danger }: { name: IconName; danger?: boolean }) {
  const { colors } = useTheme();
  return (
    <View style={[styles.icon, { backgroundColor: danger ? colors.dangerSoft : colors.primarySoft }]}>
      <Ionicons name={name} size={17} color={danger ? colors.danger : colors.primary2} />
    </View>
  );
}

// A row that opens something.
export function Row({
  icon,
  label,
  value,
  onPress,
  danger,
  hint,
  disabled,
  busy,
  chevron = true,
}: {
  icon?: IconName;
  label: string;
  value?: string;
  onPress?: () => void;
  danger?: boolean;
  hint?: string;
  disabled?: boolean;
  busy?: boolean;
  chevron?: boolean;
}) {
  const { colors } = useTheme();
  const content = (
    <>
      {icon ? <RowIcon name={icon} danger={danger} /> : null}
      <View style={styles.rowText}>
        <Text style={[styles.rowLabel, { color: danger ? colors.danger : colors.text }]} numberOfLines={2}>
          {label}
        </Text>
        {hint ? (
          <Text style={[styles.rowHint, { color: colors.muted }]} numberOfLines={3}>
            {hint}
          </Text>
        ) : null}
      </View>
      {value ? (
        <Text style={[styles.rowValue, { color: colors.muted }]} numberOfLines={1}>
          {value}
        </Text>
      ) : null}
      {busy ? <ActivityIndicator size="small" color={colors.muted} /> : null}
      {onPress && chevron && !busy ? <Ionicons name={forwardChevron()} size={18} color={colors.muted2} /> : null}
    </>
  );
  if (!onPress) {
    return (
      <View style={styles.row} accessible accessibilityLabel={value ? `${label}, ${value}` : label}>
        {content}
      </View>
    );
  }
  return (
    <Pressable
      onPress={onPress}
      disabled={disabled || busy}
      accessibilityRole="button"
      accessibilityLabel={label}
      accessibilityHint={hint}
      accessibilityValue={value ? { text: value } : undefined}
      accessibilityState={{ disabled: !!(disabled || busy), busy: !!busy }}
      style={({ pressed }) => [styles.row, pressed && { backgroundColor: colors.bg3 }, disabled && { opacity: 0.5 }]}
    >
      {content}
    </Pressable>
  );
}

// A row with an on/off switch. The whole row is the control, so a screen
// reader announces one "switch" rather than a label and a separate switch.
export function SwitchRow({
  icon,
  label,
  hint,
  value,
  onChange,
  disabled,
}: {
  icon?: IconName;
  label: string;
  hint?: string;
  value: boolean;
  onChange: (next: boolean) => void;
  disabled?: boolean;
}) {
  const { colors } = useTheme();
  const flip = () => {
    if (disabled) return;
    tick();
    onChange(!value);
  };
  return (
    <Pressable
      onPress={flip}
      disabled={disabled}
      accessibilityRole="switch"
      accessibilityLabel={label}
      accessibilityHint={hint}
      accessibilityState={{ checked: value, disabled: !!disabled }}
      style={[styles.row, disabled && { opacity: 0.5 }]}
    >
      {icon ? <RowIcon name={icon} /> : null}
      <View style={styles.rowText}>
        <Text style={[styles.rowLabel, { color: colors.text }]}>{label}</Text>
        {hint ? <Text style={[styles.rowHint, { color: colors.muted }]}>{hint}</Text> : null}
      </View>
      <View accessible={false} importantForAccessibility="no-hide-descendants" accessibilityElementsHidden>
        <Switch
          value={value}
          onValueChange={() => flip()}
          disabled={disabled}
          trackColor={{ true: colors.primary, false: colors.muted2 }}
          thumbColor="#FFFFFF"
          ios_backgroundColor={colors.muted2}
        />
      </View>
    </Pressable>
  );
}

// One choice out of several. Wrap a set in <RadioGroup>.
export function RadioRow({
  label,
  hint,
  selected,
  onPress,
  disabled,
}: {
  label: string;
  hint?: string;
  selected: boolean;
  onPress: () => void;
  disabled?: boolean;
}) {
  const { colors, isDark } = useTheme();
  return (
    <Pressable
      onPress={() => {
        if (selected) return;
        tick();
        onPress();
      }}
      disabled={disabled}
      accessibilityRole="radio"
      accessibilityLabel={label}
      accessibilityHint={hint}
      accessibilityState={{ checked: selected, disabled: !!disabled }}
      style={({ pressed }) => [styles.row, pressed && { backgroundColor: colors.bg3 }, disabled && { opacity: 0.5 }]}
    >
      <View style={styles.rowText}>
        <Text style={[styles.rowLabel, { color: colors.text }]}>{label}</Text>
        {hint ? <Text style={[styles.rowHint, { color: colors.muted }]}>{hint}</Text> : null}
      </View>
      {selected ? <Ionicons name="checkmark" size={22} color={isDark ? colors.primary2 : colors.primary} /> : null}
    </Pressable>
  );
}

export function RadioGroup({ title, footer, children }: { title?: string; footer?: string; children: ReactNode }) {
  return (
    <View accessibilityRole="radiogroup" accessibilityLabel={title}>
      <Group title={title} footer={footer}>
        {children}
      </Group>
    </View>
  );
}

// ---------- People ----------

export function Avatar({ uri, name, size = 44 }: { uri?: string | null; name?: string | null; size?: number }) {
  const { colors } = useTheme();
  const initial = (name ?? '').trim().charAt(0).toUpperCase() || '?';
  const box = { width: size, height: size, borderRadius: size / 2 };
  if (uri) {
    return (
      <Image
        source={{ uri }}
        style={[box, { backgroundColor: colors.bg3 }]}
        contentFit="cover"
        accessibilityIgnoresInvertColors
        accessible={false}
      />
    );
  }
  return (
    <View style={[box, styles.avatarFallback, { backgroundColor: colors.bg3 }]} accessible={false}>
      <Text style={{ color: colors.muted, fontWeight: '700', fontSize: size * 0.4 }}>{initial}</Text>
    </View>
  );
}

export function PersonRow({
  name,
  handle,
  avatarUrl,
  subtitle,
  actionLabel,
  onAction,
  busy,
  right,
}: {
  name: string;
  handle?: string | null;
  avatarUrl?: string | null;
  subtitle?: string;
  actionLabel?: string;
  onAction?: () => void;
  busy?: boolean;
  right?: ReactNode;
}) {
  const { colors, isDark } = useTheme();
  const sub = subtitle ?? (handle ? `@${handle}` : '');
  return (
    <View style={styles.person}>
      <Avatar uri={avatarUrl} name={name} />
      <View style={styles.rowText} accessible accessibilityLabel={sub ? `${name}, ${sub}` : name}>
        <Text style={[styles.rowLabel, { color: colors.text }]} numberOfLines={1}>
          {name}
        </Text>
        {sub ? (
          <Text style={[styles.rowHint, { color: colors.muted }]} numberOfLines={1}>
            {sub}
          </Text>
        ) : null}
      </View>
      {right}
      {actionLabel && onAction ? (
        <Pressable
          onPress={onAction}
          disabled={busy}
          accessibilityRole="button"
          accessibilityLabel={`${actionLabel}, ${name}`}
          accessibilityState={{ busy: !!busy, disabled: !!busy }}
          hitSlop={6}
          style={[styles.pill, { backgroundColor: colors.primarySoft }]}
        >
          {busy ? (
            <ActivityIndicator size="small" color={isDark ? colors.primary2 : colors.primary} />
          ) : (
            <Text style={{ color: isDark ? colors.primary2 : colors.primary, fontWeight: '700', fontSize: 13 }}>
              {actionLabel}
            </Text>
          )}
        </Pressable>
      ) : null}
    </View>
  );
}

