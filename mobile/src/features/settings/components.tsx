export function InlineError({ text }: { text?: string | null }) {
  const { colors } = useTheme();
  if (!text) return null;
  return (
    <View style={[styles.errorBox, { backgroundColor: colors.dangerSoft }]} accessibilityLiveRegion="polite">
      <AppText variant="small" style={{ color: colors.danger }} accessibilityRole="alert">
        {text}
      </AppText>
    </View>
  );
}

