// Resolves true only on the confirm button.
export function confirm({
  title,
  message,
  confirmLabel,
  cancelLabel,
  destructive,
}: {
  title: string;
  message?: string;
  confirmLabel: string;
  cancelLabel: string;
  destructive?: boolean;
}): Promise<boolean> {
  return new Promise((resolve) => {
    Alert.alert(
      title,
      message,
      [
        { text: cancelLabel, style: 'cancel', onPress: () => resolve(false) },
        { text: confirmLabel, style: destructive ? 'destructive' : 'default', onPress: () => resolve(true) },
      ],
      { cancelable: true, onDismiss: () => resolve(false) },
    );
  });
}

export function pgCode(e: unknown): string | undefined {
  const c = (e as { code?: unknown } | null)?.code;
  return typeof c === 'string' ? c : undefined;
}

// A readable sentence for a failed call. Never shows a raw Postgres message.
export function errorText(e: unknown, t: TFunction, fallbackKey = 'settings2.common.failed'): string {
  if (e instanceof ApiError) {
    if (e.code === 'content_blocked') {
      // The moderation service's own reason when it gave one.
      return e.message && e.message !== 'content_blocked' ? e.message : t('settings2.errors.contentBlocked');
    }
    if (e.code === 'support_rate_limited') return t('settings2.errors.tooManyReports');
    if (e.code === 'not_signed_in') return t('settings2.errors.signedOut');
  }
  const m = String((e as Error)?.message ?? '');
  if (/network|fetch|timed? ?out/i.test(m)) return t('errors.network');
  if (/rate limit|too many/i.test(m)) return t('errors.rateLimited');
  return t(fallbackKey);
}

export function showError(t: TFunction, e: unknown, fallbackKey?: string) {
  Alert.alert(t('settings2.common.errorTitle'), errorText(e, t, fallbackKey));
}

